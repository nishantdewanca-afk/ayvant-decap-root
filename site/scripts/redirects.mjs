// Writes public/_redirects (Netlify) before each build, from the posts' publish state.
// - A live post's old Wix URL goes to it (301).
// - A post that is scheduled or held for a rewrite sends its old URL to the Learning Hub for now (302),
//   so nothing 404s; the first build on or after its date switches that to a 301 to the post itself.
// - Retired and merged posts follow content/legacy-redirects.txt, with the same rule for their targets.
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const ROOT = path.join(process.cwd(), "..");
const OUT_FILE = path.join(process.cwd(), "public/_redirects");

// ayvant.ca (NEXT_PUBLIC_SITE=ca): its own short list, carried over from the original site's netlify.toml.
if (process.env.NEXT_PUBLIC_SITE === "ca") {
  const CITIES = ["vancouver", "langley", "burnaby", "richmond", "coquitlam", "port-moody", "delta", "abbotsford", "chilliwack"];
  const lines = [
    "# Generated by scripts/redirects.mjs at build time (ayvant.ca). Do not edit by hand.",
    "",
    "# Old short location addresses",
    ...CITIES.map((c) => `/locations/${c}/  /locations/it-support-${c}/  301`),
    "/locations/surrey/  /managed-it-services-surrey/  301",
    "/locations/it-support-surrey/  /managed-it-services-surrey/  301",
    "",
    "# Common feed addresses",
    "/rss.xml  /learning-hub/rss.xml  301",
    "/feed  /learning-hub/rss.xml  301",
    "",
    "# The blog is now the Learning Hub",
    "/blog  /learning-hub/  301",
    "/blog/*  /learning-hub/:splat  301",
    "",
    "# Old Wix addresses Google still has indexed (Search Console, Nov 2026)",
    "/contact-4  /pages/contact/  301",
    "/get-started  /pages/contact/  301",
    "/solutions  /pages/it-support/  301",
    "/vision  /pages/about/  301",
    "/post/*  /learning-hub/  301",
  ];
  fs.writeFileSync(OUT_FILE, lines.join("\n") + "\n");
  console.log(`_redirects (ca): ${lines.filter((l) => l.startsWith("/")).length} rules`);
  process.exit(0);
}
const POSTS = path.join(ROOT, "content/blog");
const LEGACY = path.join(ROOT, "content/legacy-redirects.txt");
const OUT = path.join(process.cwd(), "public/_redirects");
const today = process.env.PUBLISH_AS_OF || new Date().toLocaleDateString("en-CA", { timeZone: "America/Los_Angeles" });
const HUB = "/learning-hub";

const posts = fs.readdirSync(POSTS).filter((f) => f.endsWith(".md")).map((f) => {
  const { data: m } = matter(fs.readFileSync(path.join(POSTS, f), "utf8"));
  const date = (m.date instanceof Date ? m.date.toISOString() : String(m.date || "")).slice(0, 10);
  return { slug: String(m.slug || f.slice(0, -3)), oldUrl: m.old_url || "", live: m.published !== false && (!date || date <= today) };
});
const live = new Set(posts.filter((p) => p.live).map((p) => `${HUB}/${p.slug}`));
const rule = (from, to) => (to === HUB || live.has(to) || !to.startsWith(`${HUB}/`) ? `${from}  ${to}  301` : `${from}  ${HUB}  302`);

const lines = ["# Generated by scripts/redirects.mjs at build time. Do not edit by hand.", "", "# Imported Wix posts"];
for (const p of posts) if (p.oldUrl) lines.push(rule(p.oldUrl, `${HUB}/${p.slug}`));
lines.push("", "# Retired and merged Wix posts");
for (const l of fs.existsSync(LEGACY) ? fs.readFileSync(LEGACY, "utf8").split("\n") : []) {
  const [from, to] = l.trim().split(/\s+/);
  if (from && to && !from.startsWith("#")) lines.push(rule(from, to));
}
lines.push("", "# Anything else from the old Wix blog", `/post/*  ${HUB}  301`, `/blog  ${HUB}  301`, `/blog/*  ${HUB}  301`);
lines.push("", "# Common feed addresses, including the one the Emergent build advertised", `/api/blog/rss.xml  ${HUB}/rss.xml  301`, `/rss.xml  ${HUB}/rss.xml  301`, `/feed  ${HUB}/rss.xml  301`);
lines.push("", "# Old Emergent-only paths", "/api/*  /  301");
fs.writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`_redirects: ${lines.filter((l) => l.startsWith("/")).length} rules, ${live.size} live posts as of ${today}`);
